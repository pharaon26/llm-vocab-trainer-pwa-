import json
import re

from pydantic import ValidationError

from app.config import settings
from app.enums import TaskType
from app.llm.base import LLMProvider
from app.llm.prompts import build_prompt
from app.models import Card
from app.schemas.generation import GeneratedTask

GENERATED_TYPES = (TaskType.GAP_FILL, TaskType.COLLOCATION_CHOICE, TaskType.DEFINITION_MATCH)


class InvalidResponse(ValueError):
    pass


def parse_response(text: str) -> GeneratedTask:
    cleaned = re.sub(r"```(?:json)?", "", text)
    start, end = cleaned.find("{"), cleaned.rfind("}")
    if start == -1 or end <= start:
        raise InvalidResponse("No JSON object in the response")
    try:
        data = json.loads(cleaned[start : end + 1])
        return GeneratedTask.model_validate(data)
    except (json.JSONDecodeError, ValidationError) as exc:
        raise InvalidResponse(str(exc)) from exc


def generate_task(
    provider: LLMProvider, card: Card, task_type: TaskType, level: str | None = None
) -> GeneratedTask:
    if task_type not in GENERATED_TYPES:
        raise ValueError(f"Task type {task_type.value} is not generated by LLM")
    system, user = build_prompt(card, task_type, level or settings.student_level)
    return parse_response(provider.complete(system, user))
